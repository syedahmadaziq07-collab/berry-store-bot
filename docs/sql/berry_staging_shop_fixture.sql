CREATE TABLE public.products (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,tenant_id uuid NOT NULL REFERENCES public.tenants(id),
 name text NOT NULL,description text NOT NULL DEFAULT '',price numeric(12,2) NOT NULL CHECK(price>=0),
 stock integer NOT NULL DEFAULT 0 CHECK(stock>=0),duration text NOT NULL DEFAULT '',
 is_active boolean NOT NULL DEFAULT true,auto_delivery boolean NOT NULL DEFAULT false,
 status text NOT NULL DEFAULT 'active',account_type text,delivery_note text,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.product_variants (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,tenant_id uuid NOT NULL REFERENCES public.tenants(id),
 product_id integer NOT NULL REFERENCES public.products(id),variant_name text NOT NULL,
 price numeric(12,2) NOT NULL CHECK(price>=0),stock integer NOT NULL DEFAULT 0 CHECK(stock>=0),
 description text,delivery_note text,created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.users (
 tenant_id uuid NOT NULL REFERENCES public.tenants(id),id bigint NOT NULL CHECK(id>0),
 username text,first_name text,total_spent numeric(12,2) NOT NULL DEFAULT 0,
 referral_code text,referred_by text,created_at timestamptz NOT NULL DEFAULT now(),PRIMARY KEY(tenant_id,id)
);
-- Metadata only: deliberately no account passwords or delivery credentials.
CREATE TABLE public.credentials (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,tenant_id uuid NOT NULL REFERENCES public.tenants(id),
 product_id integer NOT NULL REFERENCES public.products(id),variant_id integer REFERENCES public.product_variants(id),
 is_used boolean NOT NULL DEFAULT false,created_at timestamptz NOT NULL DEFAULT now(),used_by_order_id text
);
CREATE TABLE public.bot_settings (
 tenant_id uuid NOT NULL REFERENCES public.tenants(id),key text NOT NULL,value text,PRIMARY KEY(tenant_id,key)
);
CREATE TABLE public.categories (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,tenant_id uuid NOT NULL REFERENCES public.tenants(id),
 name text NOT NULL,emoji text,description text,display_order integer NOT NULL DEFAULT 0,is_active boolean NOT NULL DEFAULT true
);
